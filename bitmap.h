// ============================================================================
// bitmap.h —— 24 位 BMP 位图的封装（接口声明）
//
// 设计目标：让调用者只需要关心「宽、高、颜色、某个像素」。
// BMP 格式里的文件头、像素的 BGR 顺序、每行末尾的 4 字节对齐、
// 像素自下而上存储等细节，全部隐藏在 Bitmap 类内部。
//
// 坐标约定：以左上角为原点，x 向右增大、y 向下增大，(0, 0) 是左上角那个像素。
//
// 用法示例：
//     const uint8_t orange[3] = {255, 128, 0};   // {红, 绿, 蓝}
//     Bitmap bitmap(320, 200, orange);           // 宽 320、高 200，整张橙色
//     const uint8_t red[3] = {255, 0, 0};
//     bitmap.setPixel(20, 30, red);              // 把 (20, 30) 处改成红色
//     bitmap.save("output.bmp");                 // 写盘
// ============================================================================

#ifndef BITMAP_H
#define BITMAP_H

#include <cstdint>
#include <string>
#include <vector>

// ============================================================================
// 类 Bitmap —— 一张内存中的 24 位 BMP 位图
//
//   构造时按指定颜色把整张图填满，之后可以用 setPixel() 逐个修改像素，
//   最后用 save() 按 BMP 格式写入文件。
//   一个对象对应一张图；宽、高在构造后不再改变，所以 width()/height() 是只读的。
//   因为 setPixel() 会修改对象，需要改像素的 Bitmap 不能声明成 const。
// ============================================================================
class Bitmap {
public:
    /**
     * 作用：构造一张「宽 width、高 height」的位图，并整张填成 rgb 指定的颜色。
     *       此时只在内存里准备好像素数据，尚未写任何文件。
     * 参数：width  —— 宽，水平方向的像素数，必须 > 0
     *       height —— 高，竖直方向的像素数，必须 > 0
     *       rgb    —— 颜色，3 元素数组 {红, 绿, 蓝}，每个分量取值 0~255
     * 返回：无（构造函数没有返回值；构造成功即代表对象可用）
     * 异常：width 或 height 不是正整数时抛 std::invalid_argument。
     *       异常在分配内存之前抛出，所以对象不会被建立，
     *       后续所有成员函数都不必再检查宽高是否合法。
     */
    Bitmap(int width, int height, const uint8_t (&rgb)[3]);

    // 作用：读取位图的宽（水平方向像素数）。
    // 参数：无
    // 返回：宽，单位像素，恒为正整数
    int width() const { return width_; }

    // 作用：读取位图的高（竖直方向像素数）。
    // 参数：无
    // 返回：高，单位像素，恒为正整数
    int height() const { return height_; }

    /**
     * 作用：把坐标 (x, y) 处的那个像素改成 rgb 指定的颜色。
     *       坐标以左上角为原点：x 是列号，向右增大；y 是行号，向下增大。
     * 参数：x   —— 列号（水平位置），取值 0 ~ width() - 1
     *       y   —— 行号（竖直位置），取值 0 ~ height() - 1
     *       rgb —— 新颜色，3 元素数组 {红, 绿, 蓝}，每个分量取值 0~255
     * 返回：无（改的是对象自己的像素缓冲区）
     * 异常：x 或 y 超出上述范围时抛 std::out_of_range，
     *       越界不会写坏缓冲区，也不会悄悄改到别的像素。
     */
    void setPixel(int x, int y, const uint8_t (&rgb)[3]);

    /**
     * 作用：把内存中的位图按 BMP 格式写入磁盘文件，文件内容依次为
     *       14 字节文件头 + 40 字节信息头 + 像素数据。
     * 参数：filePath —— 输出文件路径（建议以 .bmp 结尾）；
     *                   文件已存在时直接覆盖，不存在时新建。
     * 返回：成功且数据已完整落盘返回 true；
     *       无法创建文件、或写入过程中出错时返回 false。
     * 说明：本函数不抛异常，失败一律通过返回值报告。
     */
    bool save(const std::string& filePath) const;

private:
    // 作用：计算 BMP 规定的一行像素占用的字节数，
    //       即把 width * 3 向上补齐到 4 的整数倍。
    // 参数：width —— 宽，单位像素；调用前已保证为正数
    // 返回：一行的字节数（包含行末用于对齐的补 0 字节）
    static int rowStride(int width);

    int                  width_;    // 宽（像素），构造后不再改变
    int                  height_;   // 高（像素），构造后不再改变
    int                  stride_;   // 每行占用的字节数（含行末补位），setPixel 定位时要用
    std::vector<uint8_t> pixels_;   // 像素数据，已是 BMP 原生顺序：
                                    // 自下而上、每像素 BGR、每行补齐到 4 字节；
                                    // 大小 = stride_ * height_，save() 时整块写出即可
};

#endif // BITMAP_H
